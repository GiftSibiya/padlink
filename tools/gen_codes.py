"""Generate crates/padlink-core/src/codes_table.rs from python-evdev's ecodes.

    python3 tools/gen_codes.py            # (re)write the table
    python3 tools/gen_codes.py --check    # exit 1 if it would change

The Rust port must name codes exactly like the Python one: code_name() picks
the *first* alias python-evdev lists (0x130 -> BTN_A, 0x133 -> BTN_NORTH), and
code_of() accepts every name ecodes defines. Generating the table keeps that
in lockstep with the pinned python-evdev version instead of hand-copying it.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import evdev
from evdev import ecodes as E

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "crates" / "padlink-core" / "src" / "codes_table.rs"

# the tables bridge.code_name() consults, by event type
TABLES = {"EV_KEY": E.keys, "EV_ABS": E.ABS, "EV_FF": E.FF, "EV_REL": E.REL, "EV_MSC": E.MSC, "EV_SYN": E.SYN}


def first(name) -> str:
    return name[0] if isinstance(name, (list, tuple)) else name


def render() -> str:
    lines = [
        "// @generated by tools/gen_codes.py from python-evdev "
        f"{getattr(evdev, '__version__', None) or _dist_version()}. Do not edit.",
        "",
        "/// (event type, code, name), sorted: the name `code_name()` returns.",
        "pub(crate) static CODE_NAMES: &[(u16, u16, &str)] = &[",
    ]
    rows = sorted((getattr(E, ev), code, first(name)) for ev, table in TABLES.items() for code, name in table.items())
    lines += [f'    ({etype}, {code:#x}, "{name}"),' for etype, code, name in rows]
    lines += ["];", "", "/// Every integer constant in ecodes, sorted by name: what `code_of()` accepts.",
              "pub(crate) static NAMED_CODES: &[(&str, u32)] = &["]
    names = sorted(n for n in dir(E) if n.isupper() and isinstance(getattr(E, n), int))
    for n in names:
        lines.append(f'    ("{n}", {getattr(E, n):#x}),')
    lines.append("];")
    return "\n".join(lines) + "\n"


def _dist_version() -> str:
    from importlib.metadata import version
    return version("evdev")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    if OUT.exists() and OUT.read_text() == text:
        return 0
    if args.check:
        print(f"would change: {OUT.relative_to(ROOT)}")
        return 1
    OUT.write_text(text)
    print(f"wrote: {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
